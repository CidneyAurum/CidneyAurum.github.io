def esc(s: str) -> str:
    return escape(str(s), quote=True)


def content_url(value: str, *, image: bool = False) -> str | None:
    """Accept web/local URLs and resolve site-root paths from generated posts/."""
    value = unescape(value).strip()
    if not value or re.search(r"[\x00-\x20\x7f\\]", value):
        return None
    try:
        parts = urlsplit(value)
    except ValueError:
        return None
    allowed = {"http", "https"} if image else {"http", "https", "mailto"}
    if parts.scheme and parts.scheme.lower() not in allowed:
        return None
    path = parts.path
    if not parts.scheme and not parts.netloc:
        if path.startswith(("assets/", "data/", "says/")) or path in {
            "index.html", "blog.html", "says.html", "photos.html", "limbus.html",
            "about.html", "admin.html", "feed.xml",
        }:
            path = "../" + path
        elif path.startswith("_posts/") and path.endswith(".md"):
            path = path[len("_posts/"):-3] + ".html"
        elif path.endswith(".md") and not path.startswith(("/", "../")):
            path = path[:-3] + ".html"
    return urlunsplit((parts.scheme, parts.netloc, path, parts.query, parts.fragment))


def inline(md: str) -> str:
    # Parse before escaping, and never run Markdown substitutions inside HTML
    # already generated by another substitution (especially code and attributes).
    pattern = re.compile(
        r"(?P<fence>`+)(?P<code>.*?)(?P=fence)(?!`)"
        r"|(?P<image>!)?\[(?P<label>[^\]]*)\]\((?P<url>(?:[^()]|\([^()]*\))*)\)"
        r"|\*\*(?P<strong>.+?)\*\*|\*(?P<em>[^*]+)\*"
    )
    output, position = [], 0
    for match in pattern.finditer(md):
        output.append(esc(md[position:match.start()]))
        if match.group("code") is not None:
            output.append("<code>" + esc(match.group("code").strip(" ")) + "</code>")
        elif match.group("label") is not None:
            image = bool(match.group("image"))
            url = content_url(match.group("url"), image=image)
            label = match.group("label")
            if not url:
                output.append(esc(label))
            elif image:
                output.append(f'<img src="{esc(url)}" alt="{esc(label)}" loading="lazy" decoding="async">')
            else:
                external = urlsplit(url).scheme in {"http", "https"} or url.startswith("//")
                extra = ' target="_blank" rel="noopener noreferrer"' if external else ""
                output.append(f'<a href="{esc(url)}"{extra}>' + inline(label) + "</a>")
        else:
            kind = "strong" if match.group("strong") is not None else "em"
            output.append(f"<{kind}>" + inline(match.group(kind)) + f"</{kind}>")
        position = match.end()
    output.append(esc(md[position:]))
    return "".join(output)


def related_block(current, all_items):
    """按标签重合度挑最多 3 篇相关文章（构建时算好，零运行时成本）。"""
    others = [it for it in all_items if it["slug"] != current["slug"]]
    others.sort(key=lambda it: it["date"], reverse=True)
    scored = sorted(
        others,
        key=lambda it: -len(set(current.get("tags") or []) & set(it.get("tags") or [])),
    )
    picked = [it for it in scored if len(set(current.get("tags") or []) & set(it.get("tags") or [])) > 0][:3]
    if not picked:
        picked = others[:2]
    if not picked:
        return ""
    rows = "".join(
        '<a class="related-item" href="' + esc(quote(it["slug"]) + '.html') + '">'
        + '<span class="r-title">' + esc(it["title"]) + '</span>'
        + '<span class="r-meta">' + esc(it["date"]) + " · " + esc((it.get("summary") or "")[:26]) + '…</span></a>'
        for it in picked
    )
    return '<div class="related"><div class="related-head">继续阅读 · RELATED</div>' + rows + "</div>"


def pygments_css() -> str:
    """取 pygments 深色配色 CSS；未装 pygments 返回空。"""
    try:
        from pygments.formatters import HtmlFormatter
        return HtmlFormatter(style="monokai").get_style_defs(".hljs")
    except Exception:
        return ""


def pygments_highlight(code: str, lang: str) -> str | None:
    """构建时代码高亮（CI 里装了 pygments 才生效；本地无则原样返回 None）。"""
    try:
        from pygments import highlight
        from pygments.lexers import get_lexer_by_name
        from pygments.formatters import HtmlFormatter
        lexer = get_lexer_by_name(lang or "text", stripall=False)
        fmt = HtmlFormatter(nowrap=True)
        return highlight(code, lexer, fmt).rstrip("\n")
    except Exception:
        return None


def md_to_html(md: str, headings=None):
    """headings 传列表时，h2/h3 会带自增 id 并收集为 [{level,text,id}]"""
    out, lines = [], md.replace("\r\n", "\n").split("\n")
    i, in_code, code_buf, list_stack = 0, False, [], []
    code_lang, code_fence = "", ""

    def close_lists():
        while list_stack:
            out.append(f"</{'ol' if list_stack.pop() else 'ul'}>")

    def flush_code():
        code = "\n".join(code_buf)
        highlighted = pygments_highlight(code, code_lang)
        body = f'<code class="hljs">{highlighted}</code>' if highlighted is not None else f"<code>{esc(code)}</code>"
        out.append(f'<pre data-lang="{esc(code_lang)}">{body}</pre>')

    while i < len(lines):
        line = lines[i]
        fence = re.match(r"^\s{0,3}(`{3,}|~{3,})(.*)$", line)
        if fence:
            marker, info = fence.groups()
            if in_code and marker[0] == code_fence[0] and len(marker) >= len(code_fence) and not info.strip():
                flush_code()
                code_buf, in_code = [], False
            elif not in_code:
                close_lists()
                in_code = True
                code_fence = marker
                code_lang = info.strip().split()[0] if info.strip() else ""
            else:
                code_buf.append(line)
            i += 1
            continue
        if in_code:
            code_buf.append(line)
            i += 1
            continue

        m = re.match(r"^(#{1,6})\s+(.*)$", line)
        if m:
            close_lists()
            level = len(m.group(1))
            text = inline(m.group(2))
            if headings is not None and level in (2, 3):
                hid = f"toc-{len(headings) + 1}"
                headings.append({"level": level, "text": unescape(re.sub(r"<[^>]+>", "", text)), "id": hid})
                out.append(f'<h{level} id="{hid}">{text}</h{level}>')
            else:
                out.append(f"<h{level}>{text}</h{level}>")
        elif re.match(r"^\s*[-*]\s+", line):
            if not list_stack or list_stack[-1]:
                close_lists()
                list_stack.append(False)
                out.append("<ul>")
            li_text = inline(re.sub(r"^\s*[-*]\s+", "", line))
            out.append(f"<li>{li_text}</li>")
        elif re.match(r"^\s*\d+[.)]\s+", line):
            if not list_stack or not list_stack[-1]:
                close_lists()
                list_stack.append(True)
                out.append("<ol>")
            li_text = inline(re.sub(r"^\s*\d+[.)]\s+", "", line))
            out.append(f"<li>{li_text}</li>")
        elif line.strip().startswith(">"):
            close_lists()
            out.append(f"<blockquote>{inline(line.strip().lstrip('> ').strip())}</blockquote>")
        elif re.match(r"^\s*(---+|\*\*\*+)\s*$", line):
            close_lists()
            out.append("<hr>")
        elif not line.strip():
            close_lists()
        else:
            close_lists()
            out.append(f"<p>{inline(line.strip())}</p>")
        i += 1
    if in_code:
        flush_code()
    close_lists()
    return "\n".join(out)


# ---------------- front-matter 解析 ----------------

def parse_front_matter(text: str):
    """返回 (meta dict, 正文)；没有 front-matter 时 meta 为空。"""
    text = text.lstrip("\ufeff").replace("\r\n", "\n")
    lines = text.split("\n")
    if lines and lines[0].strip() == "---":
        end = next((i for i, line in enumerate(lines[1:], 1) if line.strip() == "---"), None)
        if end is not None:
            block, body = "\n".join(lines[1:end]).strip(), "\n".join(lines[end + 1:]).lstrip("\n")
            meta = {}
            for raw in block.split("\n"):
                if ":" not in raw:
                    continue
                k, v = raw.split(":", 1)
                value = v.strip()
                if value.startswith('"') and value.endswith('"'):
                    try:
                        decoded = json.loads(value)
                    except (ValueError, TypeError):
                        decoded = value[1:-1]
                    value = decoded if isinstance(decoded, str) else value
                elif len(value) >= 2 and value[0] == value[-1] == "'":
                    value = value[1:-1]
                meta[k.strip().lower()] = value
            return meta, body
    return {}, text


