def build_meta_files(entries: list):
    site = BASE_URL
    # Rebuilding unchanged content should produce the same feed.
    newest = max((entry["date"] for entry in entries), default="2026-08-29")
    built_at = datetime.fromisoformat(newest + "T12:00:00+08:00")
    if epoch := os.environ.get("SOURCE_DATE_EPOCH"):
        built_at = datetime.fromtimestamp(int(epoch), timezone.utc)
    now = format_datetime(built_at)

    rss_items = []
    for e in entries[:20]:
        desc = esc(e.get("summary") or e["title"])
        rss_items.append(
            f"<item><title>{esc(e['title'])}</title>"
            f"<link>{site}/posts/{quote(e['slug'])}.html</link>"
            f"<guid>{site}/posts/{quote(e['slug'])}.html</guid>"
            f"<pubDate>{format_datetime(datetime.fromisoformat(e['date'] + 'T12:00:00+08:00'))}</pubDate>"
            f"<description>{desc}</description></item>")
    rss = ('<?xml version="1.0" encoding="UTF-8"?>'
           '<rss version="2.0"><channel>'
           f"<title>{esc(SITE['name'])}</title><link>{site}/</link>"
           f"<description>{esc(SITE['desc'])}</description><language>zh-CN</language>"
           f"<lastBuildDate>{now}</lastBuildDate>"
           + "".join(rss_items) + "</channel></rss>")
    (ROOT / "feed.xml").write_text(rss, encoding="utf-8")
    print("  RSS   feed.xml")

    urls = ["", "blog.html", "says.html", "photos.html", "about.html", "limbus.html"] + [
        f"posts/{quote(e['slug'])}.html" for e in entries
    ]
    post_dates = {f"posts/{quote(e['slug'])}.html": e["date"] for e in entries}
    sm_items = "".join(
        f"<url><loc>{site}/{u}</loc>"
        + (f"<lastmod>{post_dates[u]}</lastmod>" if u in post_dates else "")
        + "</url>"
        for u in urls
    )
    sm = ('<?xml version="1.0" encoding="UTF-8"?>'
          '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">' + sm_items + "</urlset>")
    (ROOT / "sitemap.xml").write_text(sm, encoding="utf-8")
    print("  SEO   sitemap.xml")

    robots = f"User-agent: *\nAllow: /\nSitemap: {site}/sitemap.xml\n"
    (ROOT / "robots.txt").write_text(robots, encoding="utf-8")
    print("  SEO   robots.txt")


