def photo_created_month(path: Path) -> str:
    """Keep undated images at their original upload month across deployments."""
    try:
        result = subprocess.run(
            ["git", "log", "--follow", "--diff-filter=A", "-1", "--format=%cs", "--", str(path.relative_to(ROOT))],
            cwd=ROOT, capture_output=True, text=True, check=True, timeout=10,
        )
        value = result.stdout.strip()
        if re.fullmatch(r"\d{4}-\d{2}-\d{2}", value):
            return value[:7]
    except (OSError, ValueError, subprocess.SubprocessError):
        pass
    return os.environ.get("PHOTO_DATE", "").strip() or "MEMORY"


def build_photos() -> list:
    if not GALLERY_DIR.exists():
        GALLERY_DIR.mkdir(parents=True)
    items = []
    for f in sorted(GALLERY_DIR.iterdir()):
        if not f.is_file() or f.suffix.lower() not in IMG_EXT:
            continue
        stem = f.stem
        m = re.search(r"_(\d{4})-(0?[1-9]|1[0-2])$", stem)
        when = f"{m.group(1)} · {int(m.group(2)):02d}" if m else photo_created_month(f)
        caption = re.sub(r"_?\d{4}-\d{1,2}$", "", stem)
        caption = re.sub(r"__upload-[0-9a-f]{10}$", "", caption) or "无题"
        items.append({"src": f"assets/gallery/{f.name}", "caption": caption, "when": when})
        print(f"  照片  {f.name}  →  「{caption}」 {when}")
    (GALLERY_DIR / "gallery.json").write_text(
        json.dumps({"photos": items}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"  目录  assets/gallery/gallery.json（共 {len(items)} 张）")
    return items


